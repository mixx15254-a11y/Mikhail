def build_markdown():
    out = []
    for kind, text in CONTENT:
        if kind == "title":
            out.append(f"# {text}\n")
        elif kind == "subtitle":
            out.append(f"**{text}**\n")
        elif kind == "h1":
            out.append(f"\n## {text}\n")
        elif kind in ("p", "small"):
            if text:
                out.append(text + "\n")
        elif kind == "bullet":
            out.append(f"– {text}\n")
        elif kind == "center":
            out.append(text + "\n")
        elif kind == "table":
            rows = text
            header = rows[0]
            out.append("| " + " | ".join(header) + " |")
            out.append("|" + "|".join(["---"] * len(header)) + "|")
            for r in rows[1:]:
                out.append("| " + " | ".join(str(c) for c in r) + " |")
            out.append("")
    return "\n".join(out)


