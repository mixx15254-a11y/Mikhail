def build_pdf():
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import cm, mm
    from reportlab.lib import colors
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.enums import TA_JUSTIFY, TA_CENTER, TA_LEFT
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer, Table,
                                    TableStyle, PageBreak)

    fdir = "/usr/share/fonts/truetype/dejavu"
    pdfmetrics.registerFont(TTFont("DJS", f"{fdir}/DejaVuSerif.ttf"))
    pdfmetrics.registerFont(TTFont("DJS-Bold", f"{fdir}/DejaVuSerif-Bold.ttf"))
    pdfmetrics.registerFontFamily("DJS", normal="DJS", bold="DJS-Bold",
                                  italic="DJS", boldItalic="DJS-Bold")

    body = ParagraphStyle("body", fontName="DJS", fontSize=9.2, leading=12.6,
                          alignment=TA_JUSTIFY, spaceAfter=3.5)
    bullet = ParagraphStyle("bullet", parent=body, leftIndent=12, firstLineIndent=0)
    h1 = ParagraphStyle("h1", parent=body, fontName="DJS-Bold", fontSize=10.5,
                        leading=13, alignment=TA_LEFT, spaceBefore=9, spaceAfter=4)
    title = ParagraphStyle("title", parent=body, fontName="DJS-Bold", fontSize=16,
                           leading=20, alignment=TA_CENTER, spaceAfter=3)
    subtitle = ParagraphStyle("subtitle", parent=body, fontName="DJS-Bold", fontSize=11.5,
                              leading=15, alignment=TA_CENTER, spaceAfter=1)
    center = ParagraphStyle("center", parent=body, alignment=TA_CENTER, spaceAfter=0)
    small = ParagraphStyle("small", parent=body, fontSize=8.4, leading=11,
                           textColor=colors.HexColor("#333333"))
    cell = ParagraphStyle("cell", parent=body, fontSize=7.6, leading=9.6,
                          alignment=TA_CENTER, spaceAfter=0)
    cellh = ParagraphStyle("cellh", parent=cell, fontName="DJS-Bold")
    cellbig = ParagraphStyle("cellbig", parent=cell, alignment=TA_LEFT)

    story = []
    for kind, text in CONTENT:
        import html
        esc = html.escape(str(text))
        if kind == "center":
            story.append(Paragraph(esc, center if text else body))
        elif kind == "title":
            story.append(Paragraph(esc, title))
        elif kind == "subtitle":
            story.append(Paragraph(esc, subtitle))
        elif kind == "h1":
            story.append(Paragraph(esc, h1))
        elif kind == "p":
            if text:
                story.append(Paragraph(esc, body))
            else:
                story.append(Spacer(1, 4))
        elif kind == "small":
            story.append(Paragraph(esc, small))
        elif kind == "bullet":
            story.append(Paragraph("– " + esc, bullet))
        elif kind == "pagebreak":
            story.append(PageBreak())
        elif kind == "table":
            rows = text
            ncols = len(rows[0])
            data = []
            for ri, row in enumerate(rows):
                cells = []
                for ci, c in enumerate(row):
                    if ri == 0:
                        st = cellh
                    elif ncols == 3:
                        st = cellbig if ci == 2 else cell
                    else:
                        st = cellbig if len(str(c)) > 25 else cell
                    cells.append(Paragraph(html.escape(str(c)), st))
                data.append(cells)
            if ncols == 7:
                widths = [0.9 * cm, 4.6 * cm, 1.9 * cm, 3.3 * cm, 1.4 * cm, 1.5 * cm, 2.2 * cm]
            elif ncols == 2:
                widths = [5.4 * cm, 11.6 * cm]
            elif ncols == 3:
                widths = [3.4 * cm, 2.6 * cm, 11.0 * cm]
            else:
                widths = None
            tbl = Table(data, colWidths=widths, repeatRows=1)
            tbl.setStyle(TableStyle([
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#666666")),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e8e8e8")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 2),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
                ("LEFTPADDING", (0, 0), (-1, -1), 3),
                ("RIGHTPADDING", (0, 0), (-1, -1), 3),
            ]))
            story.append(Spacer(1, 3))
            story.append(tbl)
            story.append(Spacer(1, 6))

    def on_page(canv, doc_):
        canv.saveState()
        canv.setFont("DJS", 8)
        canv.setFillColor(colors.HexColor("#555555"))
        canv.drawString(2.2 * cm, 1.0 * cm,
                        "Турнир «Футбольные звёзды» · 3–4 октября 2026 г. · г. Самара, стадион ЦСК ВВС")
        canv.drawRightString(A4[0] - 1.6 * cm, 1.0 * cm, "стр. " + str(canv.getPageNumber()))
        canv.setStrokeColor(colors.HexColor("#cccccc"))
        canv.line(2.2 * cm, 1.35 * cm, A4[0] - 1.6 * cm, 1.35 * cm)
        canv.restoreState()

    pdf = SimpleDocTemplate(PDF_PATH, pagesize=A4,
                            leftMargin=2.2 * cm, rightMargin=1.6 * cm,
                            topMargin=1.8 * cm, bottomMargin=1.8 * cm,
                            title="Положение о проведении турнира «Футбольные звёзды»",
                            author="Оргкомитет турнира «Футбольные звёзды»")
    pdf.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return PDF_PATH


