def build_docx():
    from docx import Document
    from docx.shared import Pt, Cm, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.enum.table import WD_TABLE_ALIGNMENT
    from docx.oxml.ns import qn
    from docx.oxml import OxmlElement

    FONT = "Times New Roman"
    doc = Document()

    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21), Cm(29.7)
    sec.top_margin, sec.bottom_margin = Cm(2), Cm(2)
    sec.left_margin, sec.right_margin = Cm(2.5), Cm(1.5)

    style = doc.styles["Normal"]
    style.font.name = FONT
    style.font.size = Pt(12)
    style.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    pf = style.paragraph_format
    pf.space_after = Pt(4)
    pf.line_spacing = 1.15
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    def add_runs(par, text, bold=False, size=12):
        """Добавляет текст, подсвечивая поля для заполнения (____)."""
        pattern = re.compile(r"(_{3,})")
        for part in pattern.split(text):
            if not part:
                continue
            run = par.add_run(part)
            run.font.name = FONT
            run.font.size = Pt(size)
            run.bold = bold
            run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
            if pattern.fullmatch(part):
                run.font.highlight_color = 7  # жёлтая подсветка: поле для заполнения
        return par

    def para(text, align=WD_ALIGN_PARAGRAPH.JUSTIFY, bold=False, size=12,
             space_before=0, space_after=4, indent=None):
        p = doc.add_paragraph()
        p.alignment = align
        p.paragraph_format.space_before = Pt(space_before)
        p.paragraph_format.space_after = Pt(space_after)
        if indent is not None:
            p.paragraph_format.left_indent = Cm(indent)
        add_runs(p, text, bold=bold, size=size)
        return p

    for kind, text in CONTENT:
        if kind == "center":
            para(text, align=WD_ALIGN_PARAGRAPH.CENTER, space_after=0)
        elif kind == "title":
            para(text, align=WD_ALIGN_PARAGRAPH.CENTER, bold=True, size=16,
                 space_before=6, space_after=2)
        elif kind == "subtitle":
            para(text, align=WD_ALIGN_PARAGRAPH.CENTER, bold=True, size=13, space_after=1)
        elif kind == "h1":
            para(text, align=WD_ALIGN_PARAGRAPH.LEFT, bold=True, size=13,
                 space_before=10, space_after=4)
        elif kind == "small":
            para(text, size=11, space_after=4)
        elif kind == "bullet":
            para("– " + text, indent=0.6, space_after=3)
        elif kind == "p":
            if text:
                para(text)
        elif kind == "pagebreak":
            doc.add_page_break()
        elif kind == "table":
            rows = text
            ncols = len(rows[0])
            t = doc.add_table(rows=len(rows), cols=ncols)
            t.style = "Table Grid"
            t.alignment = WD_TABLE_ALIGNMENT.CENTER
            for ri, row in enumerate(rows):
                for ci, val in enumerate(row):
                    cell = t.cell(ri, ci)
                    cell.text = ""
                    p = cell.paragraphs[0]
                    if ri == 0:
                        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                    elif ncols == 3:  # программа турнира: текст — по левому краю
                        p.alignment = WD_ALIGN_PARAGRAPH.LEFT if ci == 2 else WD_ALIGN_PARAGRAPH.CENTER
                    else:
                        p.alignment = WD_ALIGN_PARAGRAPH.CENTER if len(str(val)) < 30 \
                            else WD_ALIGN_PARAGRAPH.LEFT
                    p.paragraph_format.space_after = Pt(1)
                    p.paragraph_format.space_before = Pt(1)
                    add_runs(p, str(val), bold=(ri == 0), size=10)
            if ncols == 7 and len(rows) > 10:  # заявка: узкие служебные колонки
                widths = [Cm(0.9), Cm(4.6), Cm(1.9), Cm(3.3), Cm(1.4), Cm(1.5), Cm(2.2)]
                for ri in range(len(rows)):
                    for ci, w in enumerate(widths):
                        t.cell(ri, ci).width = w
            doc.add_paragraph().paragraph_format.space_after = Pt(0)
            for p in doc.paragraphs[-1:]:
                p.paragraph_format.space_after = Pt(2)

    # нумерация страниц в подвале
    footer_p = sec.footer.paragraphs[0]
    footer_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pre = footer_p.add_run("Турнир «Футбольные звёзды» · 3–4 октября 2026 г. · г. Самара, стадион ЦСК ВВС  ·  стр. ")
    pre.font.name = FONT
    pre.font.size = Pt(9)
    run = footer_p.add_run()
    run.font.name = FONT
    run.font.size = Pt(9)
    f1 = OxmlElement("w:fldChar"); f1.set(qn("w:fldCharType"), "begin")
    it = OxmlElement("w:instrText"); it.set(qn("xml:space"), "preserve"); it.text = "PAGE"
    f2 = OxmlElement("w:fldChar"); f2.set(qn("w:fldCharType"), "end")
    run._r.append(f1); run._r.append(it); run._r.append(f2)

    doc.save(DOCX_PATH)
    return DOCX_PATH


